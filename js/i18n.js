  var active;

  function detect() {
    var raw = null;
    try {
      var p = new URLSearchParams(window.location.search);
      var q = p.get('lang');
      if (q) raw = q;
    } catch (e) {}
    if (!raw) {
      try { raw = window.localStorage.getItem(LS_KEY); } catch (e) {}
    }
    if (!raw) {
      try {
        var nav = (window.navigator.language || 'es').toLowerCase().replace(/_/g, '-');
        if (nav.indexOf('fr') === 0) raw = 'fr';
        else if (nav.indexOf('es') === 0) raw = 'es';
        else if (nav.indexOf('en') === 0) raw = 'en';
      } catch (e) {}
    }
    raw = String(raw || '').toLowerCase();
    if (!SUPPORTED[raw]) raw = 'es';
    return raw;
  }

  function t(key, vars) {
    var d = DICT[active] || DICT.es;
    var s = d[key];
    if (s === undefined || s === null) s = DICT.es[key];
    if (s === undefined || s === null) s = key;
    s = String(s);
    if (vars) {
      for (var k in vars) {
        if (Object.prototype.hasOwnProperty.call(vars, k)) {
          s = s.split('{' + k + '}').join(String(vars[k] == null ? '' : vars[k]));
        }
      }
    }
    return s;
  }

  function apply() {
    var root = document;
    var el = root.querySelector('html');
    if (el) el.setAttribute('lang', active);
    var titleEl = root.querySelector('title[data-i18n]');
    if (titleEl) document.title = t(titleEl.getAttribute('data-i18n'));
    var nodes = root.querySelectorAll('[data-i18n], [data-i18n-ph], [data-i18n-title], [data-i18n-aria], [data-i18n-meta]');
    for (var i = 0; i < nodes.length; i++) {
      var n = nodes[i];
      var k;
      k = n.getAttribute('data-i18n');
      if (k) n.textContent = t(k);
      k = n.getAttribute('data-i18n-ph');
      if (k) n.setAttribute('placeholder', t(k));
      k = n.getAttribute('data-i18n-title');
      if (k) n.setAttribute('title', t(k));
      k = n.getAttribute('data-i18n-aria');
      if (k) n.setAttribute('aria-label', t(k));
      k = n.getAttribute('data-i18n-meta');
      if (k) n.setAttribute('content', t(k));
    }
    updateSwitcher();
  }

